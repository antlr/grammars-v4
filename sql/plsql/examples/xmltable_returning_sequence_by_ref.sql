-- RETURNING SEQUENCE BY REF without PASSING or COLUMNS.
SELECT * FROM XMLTABLE('/x' RETURNING SEQUENCE BY REF);

-- RETURNING SEQUENCE BY REF after an XML passing clause.
SELECT * FROM XMLTABLE('/x' PASSING BY VALUE xml_col RETURNING SEQUENCE BY REF);

-- RETURNING SEQUENCE BY REF before the COLUMNS clause.
SELECT * FROM XMLTABLE('/x' RETURNING SEQUENCE BY REF COLUMNS id VARCHAR2(10) PATH 'id');

-- RETURNING SEQUENCE BY REF between the XML passing and COLUMNS clauses.
SELECT * FROM XMLTABLE('/x' PASSING xml_col RETURNING SEQUENCE BY REF COLUMNS id VARCHAR2(10) PATH 'id');
