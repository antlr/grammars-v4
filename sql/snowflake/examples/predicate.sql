-- Predicates in WHERE
SELECT a FROM t WHERE a IS NULL;
SELECT a FROM t WHERE a IS NOT NULL;
SELECT a FROM t WHERE a IN (1, 2, 3);
SELECT a FROM t WHERE a NOT IN ('x', 'y');
SELECT a FROM t WHERE a IN (SELECT b FROM u);
SELECT a FROM t WHERE a NOT IN (SELECT b FROM u);
SELECT a FROM t WHERE a LIKE 'x%';
SELECT a FROM t WHERE a LIKE 'x!%%' ESCAPE '!';
SELECT a FROM t WHERE a NOT ILIKE '%y%';
SELECT a FROM t WHERE a RLIKE '[0-9]+';
SELECT a FROM t WHERE a NOT RLIKE '[a-z]+';
SELECT a FROM t WHERE a LIKE ANY ('x%', 'y%');
SELECT a FROM t WHERE a NOT ILIKE ANY ('x%', 'y%') ESCAPE '!';
SELECT a FROM t WHERE a BETWEEN 1 AND 5;
SELECT a FROM t WHERE a NOT BETWEEN 1 AND 5;
SELECT a FROM t WHERE EXISTS (SELECT 1 FROM u WHERE u.b = t.a);
SELECT a FROM t WHERE NOT EXISTS (SELECT 1 FROM u WHERE u.b = t.a);

-- Quantified subquery comparisons
SELECT a FROM t WHERE a = ANY (SELECT b FROM u);
SELECT a FROM t WHERE a <> ALL (SELECT b FROM u);
SELECT a FROM t WHERE a > SOME (SELECT b FROM u);

-- Predicates combined with AND, OR and NOT
SELECT a FROM t WHERE a = 1 AND b IS NOT NULL OR c NOT LIKE 'z%';
SELECT a FROM t WHERE NOT (a IN (1, 2) OR b RLIKE '^x');

-- Predicates in CASE WHEN
SELECT CASE WHEN a IS NULL THEN 0 WHEN a NOT IN (1, 2) AND b LIKE 'x%' THEN 1 ELSE 2 END FROM t;
SELECT CASE WHEN UPPER(a) = 'X' AND b BETWEEN 1 AND 5 THEN 'in range' WHEN c ILIKE ANY ('p%', 'q%') THEN 'match' END FROM t;
SELECT SUM(CASE WHEN a = ANY (SELECT b FROM u) THEN 1 ELSE 0 END) FROM t;
