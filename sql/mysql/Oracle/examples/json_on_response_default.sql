-- DEFAULT in an ON EMPTY or ON ERROR clause takes a literal of the returned type,
-- not only a string (json_on_response: DEFAULT_SYM signed_literal in sql_yacc.yy).
-- That literal is never NULL (NULL ON EMPTY is the form for it), and only a number takes a sign.
SELECT JSON_VALUE(j, '$.a' RETURNING UNSIGNED DEFAULT 0 ON EMPTY) FROM t;
SELECT JSON_VALUE(j, '$.a' RETURNING SIGNED DEFAULT -1 ON EMPTY DEFAULT -2 ON ERROR) FROM t;
SELECT JSON_VALUE(j, '$.a' RETURNING DECIMAL(10,2) DEFAULT 1.5 ON ERROR) FROM t;
SELECT JSON_VALUE(j, '$.a' DEFAULT 'none' ON EMPTY ERROR ON ERROR) FROM t;
SELECT jt.a FROM t, JSON_TABLE(t.j, '$[*]' COLUMNS (a INT PATH '$.a' DEFAULT '0' ON EMPTY NULL ON ERROR)) AS jt;
SELECT JSON_VALUE('{}', '$.a' RETURNING DECIMAL(10,2) DEFAULT -1.5 ON EMPTY) AS v;
SELECT JSON_VALUE('{}', '$.a' RETURNING DOUBLE DEFAULT -1.5e3 ON EMPTY) AS v;
SELECT JSON_VALUE('{}', '$.a' RETURNING DATE DEFAULT DATE '2000-01-01' ON EMPTY) AS v;
SELECT JSON_VALUE('{}', '$.a' RETURNING SIGNED DEFAULT TRUE ON EMPTY DEFAULT +2 ON ERROR) AS v;
SELECT JSON_VALUE('{}', '$.a' DEFAULT 'a' 'b' ON EMPTY) AS v, JSON_VALUE('{}', '$.a' DEFAULT N'x' ON EMPTY) AS w;
SELECT JSON_VALUE('{}', '$.a' DEFAULT 0x41 ON EMPTY) AS v, JSON_VALUE('{}', '$.a' DEFAULT b'1000001' ON EMPTY) AS w;
SELECT JSON_VALUE('{}', '$.a' NULL ON EMPTY NULL ON ERROR) AS v;
